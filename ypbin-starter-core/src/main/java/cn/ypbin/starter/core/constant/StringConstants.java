package cn.ypbin.starter.core.constant;

/**
 * 常用字符串常量。
 *
 * <p>集中管理散落各处的字面量，避免硬编码与拼写不一致。</p>
 *
 * @author wenbin
 * @since 2026-07-30
 */
public interface StringConstants {

    /** 空字符串 */
    String EMPTY = "";

    /** 空格 */
    String SPACE = " ";

    /** 点 */
    String DOT = ".";

    /** 逗号 */
    String COMMA = ",";

    /** 冒号 */
    String COLON = ":";

    /** 分号 */
    String SEMICOLON = ";";

    /** 斜杠 */
    String SLASH = "/";

    /** 反斜杠 */
    String BACKSLASH = "\\";

    /** 下划线 */
    String UNDERLINE = "_";

    /** 中划线 */
    String DASHED = "-";

    /** 星号 */
    String ASTERISK = "*";

    /** 与号 */
    String AMP = "&";

    /** 问号 */
    String QUESTION_MARK = "?";

    /** 等号 */
    String EQUALS = "=";

    /** 左大括号 */
    String DELIM_START = "{";

    /** 右大括号 */
    String DELIM_END = "}";
}
